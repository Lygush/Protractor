#pragma once
#include <Arduino.h>

// ============================================================================
//  Карта памяти на внешней W25Q32 (4 МБ, сектор стирания = 4 КБ, страница = 256 Б)
//  Данных у нас на пару килобайт, поэтому не мудрим: каждый блок — с начала
//  своего сектора, стирание идёт по секторам, адресация плоская.
//  Этот файл должен быть ОДИНАКОВЫМ в обоих проектах (Writer и основная
//  прошивка) — смещения тут жёстко зашиты в обе стороны.
// ============================================================================

#define FLASH_SECTOR_SIZE   4096UL
#define FLASH_PAGE_SIZE     256UL

// Сектор 0: DMP-прошивка для MPU6050 (dmpMemory[], 1929 байт)
#define ADDR_DMP_MEMORY     (0UL * FLASH_SECTOR_SIZE)     // 0x000000
#define SIZE_DMP_MEMORY     1929UL

// Сектор 1: полная таблица шрифта GyverOLED (_charMap, 95 символов x 5 байт = 475 байт)
// Хранится ЦЕЛИКОМ, включая "горячие" глифы (цифры/пробел/минус/точка) —
// они дополнительно продублированы в основной прошивке в локальной PROGMEM
// таблице ради скорости отрисовки на каждый кадр. Индексация здесь СОВПАДАЕТ
// один в один с оригинальным индексом строки в _charMap — переносить логику
// getFont() не нужно, меняется только источник байта.
#define ADDR_CHARMAP        (1UL * FLASH_SECTOR_SIZE)     // 0x001000
#define SIZE_CHARMAP_ROWS   95UL
#define SIZE_CHARMAP        (SIZE_CHARMAP_ROWS * 5UL)      // 475 байт

// Сектор 2: иконки (battery/mode/circle/arrows), рисуются только при
// перерисовке базового экрана — не на каждый кадр, задержка SPI-чтения не
// критична. Также здесь же хранится лого-заставка (frog_128x64, 1024 байта) —
// пока только записана на флеш, отрисовка не подключена (см. Задачи.txt).
#define ADDR_ICONS          (2UL * FLASH_SECTOR_SIZE)     // 0x002000
#define SIZE_ICONS_TOTAL    1256UL

// Сектор 3: заголовок с контрольными суммами — основная прошивка при
// старте сверяет их и, если не совпало (прошивка flash не выполнена или
// побилась), падает в понятный стоп-режим вместо непредсказуемого поведения.
#define ADDR_HEADER          (3UL * FLASH_SECTOR_SIZE)     // 0x003000
#define HEADER_MAGIC         0xA55AF017UL

struct FlashHeader {
    uint32_t magic;
    uint16_t crc_dmp;
    uint16_t crc_charmap;
    uint16_t crc_icons;
};

// Сколько всего секторов нужно стереть перед записью (0..3 включительно)
#define FLASH_SECTORS_USED   4UL
